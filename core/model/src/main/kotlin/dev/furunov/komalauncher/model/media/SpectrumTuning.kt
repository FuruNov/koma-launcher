package dev.furunov.komalauncher.model.media

/**
 * ビジュアライザーの棒の計算で調整する値。アプリは既定の値を使い、記録の再生（tools/vis-replay）で別の値と比べる。
 * 大きさは、全振幅の正弦波を 0dB とする。getFft の値（全振幅の正弦波で約 512）で決めた以前の閾値からは、54dB を引くと換算できる。
 */
data class SpectrumTuning(
    /** 最近の最大から何 dB 下までを棒の高さにするか。帯域の大きさは 20ms ごとに 3.5dB ほど変わるので、実機で敏感すぎると指摘があり 20 から広げた。 */
    val windowDb: Float = 30f,
    /**
     * 最近の最大が 1 秒に下がる大きさ（dB）と、棒の高さを何乗するか。実機で棒が全体的に高いと指摘があり、2 と 1.5 から変えた。
     * 実機の記録（約 20 秒）で計算すると、平均の高さは 0.66 から 0.45 に、9 割を超える時間は 23% から 7% に下がり、
     * フレームごとの変化は 0.045 から 0.055 に増えるだけだった。
     */
    val decayDb: Float = 0.5f,
    val contrast: Float = 3f,
    /**
     * 大きさを時間方向に平均する時定数（秒）。1 区画だけの帯域は、取得（21ms）ごとに数 dB ばらつく。棒の範囲を広げ、上がる速さを下げても、
     * 実機で敏感すぎるという見え方は変わらなかったので、棒にする前の大きさを平均する。
     */
    val tauSec: Float = 0.08f,
    /** これより小さい音は無音とみなす。波形の ±1 の揺れは 1 区画あたり平均 -64dB で、区画ごとにばらつくので、9dB 上に置く。 */
    val gateDb: Float = -55f,
    /**
     * 最近の最大の下限。静かな部分で、小さい音まで棒いっぱいに広げないように。以前の getFft の値で、[gateDb] から 24dB 上に置いていた
     * （実機で揺れすぎると指摘があり、差を 14dB から広げた）ので、その差を保つ。実機（2026-11-21、YT Music）の 1 オクターブごとの
     * 平均は、低音〜中音域が -16〜-29dB、2kHz より上が -35〜-53dB だった。
     */
    val minPeakDb: Float = -31f,
    /** 棒が上がる速さと下がる速さ（1 秒あたり、差のうち寄せる割合）。実機で敏感すぎると指摘があり、上がる速さを 30 から下げた。 */
    val rise: Float = 15f,
    val fall: Float = 6f,
    /**
     * 音量の分を戻した RMS がこれより小さければ無音とみなす（全振幅の正弦波の RMS が -3dB）。実機（2026-11-21、YT Music）では、
     * 曲が鳴っている間は -8〜-12dB だった。RMS は最大 25 処理単位の平均なので、音が止まってから下がりきるまで 1〜2 秒かかる。
     */
    val quietDb: Float = -50f,
) {
    /**
     * NORMALIZED は、曲間やフェードアウトのごく小さい音も最大まで大きくするので、波形からは無音に近いことが分からない。
     * 正規化の前の RMS（[rmsDb]、音量をかけた後）から音量（[volumeDb]、0 以下）の分を戻して判断する。RMS が分からなければ false。
     */
    fun isQuiet(
        rmsDb: Float,
        volumeDb: Float,
    ): Boolean = !rmsDb.isNaN() && rmsDb - volumeDb < quietDb
}
